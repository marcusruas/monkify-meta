// Writes the posting sheet: every piece with its caption, hashtags and suggested day.
//
//   node tools/captions.mjs <campaign-slug>
//
// Output: out/<slug>/CAPTIONS.md
//
// Why this exists: an image never travels alone, and the person publishing should be able to work
// from ONE file instead of opening a JavaScript module to find the caption for a PNG. `still.md`
// §6 requires the caption to ship with the piece; without this tool that requirement had nowhere
// to land.
//
// ⚠️ Links are printed UNTAGGED on purpose. A UTM tag is per channel and per placement, so it
// cannot be baked into artwork and should not be frozen into a caption either — see
// marketing/utm-conventions.md, and add the tag when you paste the link.

import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { BOARDS, FORMATS } from './boards.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const slug = process.argv[2];
if (!slug) throw new Error('usage: node tools/captions.mjs <campaign-slug>');

const DIR = join(here, '..', 'campaigns', slug);
const OUT = join(here, '..', 'out', slug);
if (!existsSync(join(DIR, 'content.mjs'))) throw new Error(`no campaign at ${DIR}`);

const content = await import(pathToFileURL(join(DIR, 'content.mjs')).href);
const campaign = content.campaign ?? {};
const stills = content.stills ?? [];
const video = content.video ?? null;

const tags = (list) => (list?.length ? list.map((h) => `#${h}`).join(' ') : '_none_');

const lines = [];
lines.push(`# ${slug} — posting sheet`);
lines.push('');
lines.push('> Generated by `tools/captions.mjs`. Do not edit here — edit');
lines.push('> `campaigns/' + slug + '/content.mjs` and regenerate, or the sheet and the pieces drift apart.');
lines.push('');
if (campaign.handle) lines.push(`**Handle:** ${campaign.handle}  `);
if (campaign.url) lines.push(`**Link:** ${campaign.url}`);
lines.push('');

if (campaign.notes?.length) {
  lines.push('## Decisions recorded with this campaign');
  lines.push('');
  for (const n of campaign.notes) lines.push(`- ${n}`);
  lines.push('');
}

lines.push('## Before posting');
lines.push('');
lines.push('- [ ] Tag the link with `utm_source` / `utm_medium` / `utm_campaign` (`marketing/utm-conventions.md`).');
lines.push('- [ ] Run the pre-publish checklist in `references/compliance.md` §7.');
lines.push('- [ ] Check the safe zone for the surface: `node tools/proof.mjs ' + slug + ' <surface>`.');
lines.push('');
lines.push('---');
lines.push('');

if (stills.length) {
  lines.push('## Stills');
  lines.push('');
  for (const p of stills) {
    const b = BOARDS[p.board];
    lines.push(`### ${p.id}`);
    lines.push('');
    lines.push(`**File:** \`out/${slug}/png/${p.id}.png\` · **${b.where}** · **when:** ${p.when ?? '—'}`);
    lines.push('');
    lines.push('```');
    lines.push(p.caption ?? '(no caption written)');
    lines.push('```');
    lines.push('');
    lines.push(tags(p.hashtags));
    lines.push('');
  }
}

if (video) {
  const f = FORMATS[video.format];
  const ms = video.scenes.reduce((n, s) => n + s.ms, 0);
  lines.push('## Video');
  lines.push('');
  lines.push(`### ${video.id}`);
  lines.push('');
  lines.push(`**File:** \`out/${slug}/${video.id}.mp4\` · **${f.where}** · **${(ms / 1000).toFixed(1)}s**`);
  lines.push('');
  if (video.format === 'reels') {
    lines.push(`Slideshow cut: \`out/${slug}/slides/\` (inset framing, TikTok photo mode) — regenerate the`);
    lines.push(`Stories framing with \`node tools/slides.mjs ${slug} overlaid\`.`);
    lines.push('');
    lines.push('⚠️ **For Reels and TikTok, consider posting the silent cut** and picking a trending sound in');
    lines.push('the app: it helps distribution and the licence is handled there.');
    lines.push('');
    lines.push(`    node tools/render.mjs ${slug} --silent`);
    lines.push('');
    lines.push('⚠️ Instagram on the **web** has no sound picker, so a silent file posted from a desktop stays');
    lines.push('a silent Reel. Post the sounded cut there, or post from the phone.');
    lines.push('');
  } else {
    // A landscape piece has no slideshow cut: swiping stills is a 9:16 idea.
    lines.push('⚠️ **X autoplays video MUTED in the timeline**, so this has to land with the sound off.');
    lines.push('It does: every beat is on-screen type. The soundtrack is there for anyone who unmutes.');
    lines.push('');
    lines.push('⚠️ **Post the video on its own.** X takes one video per post, and a 16:9 is shown whole —');
    lines.push('this is the one shape its timeline never crops.');
    lines.push('');
  }
  if (video.caption) {
    // The character count is printed because X hard-caps at 280 and an over-long post is
    // truncated at publish time, usually mid-sentence.
    const body = video.caption + (video.hashtags?.length ? '\n\n' + tags(video.hashtags) : '');
    const n = [...body].length;
    lines.push(`**Post text** — ${n} characters${n > 280 ? ' ⚠️ OVER the 280 limit' : ' of 280'}`);
    lines.push('');
    lines.push('```');
    lines.push(body);
    lines.push('```');
    lines.push('');
    if (video.reply) {
      lines.push('**First reply** — the link lives here, never in the main tweet body');
      lines.push('(marketing/twitter-launch-campaign.md §6).');
      lines.push('');
      lines.push('```');
      lines.push(video.reply);
      lines.push('```');
      lines.push('');
    }
  }
  lines.push('**Scenes**');
  lines.push('');
  lines.push('| # | id | ms | headline |');
  lines.push('| --- | --- | ---: | --- |');
  video.scenes.forEach((s, i) => {
    const h = String(s.headline ?? '').replace(/<br>/g, ' ').replace(/<\/?em>/g, '').replace(/\|/g, '\\|');
    lines.push(`| ${i + 1} | ${s.id} | ${s.ms} | ${h} |`);
  });
  lines.push('');
}

mkdirSync(OUT, { recursive: true });
const file = join(OUT, 'CAPTIONS.md');
writeFileSync(file, lines.join('\n'), 'utf8');
console.log(`${stills.length} stills${video ? ' + 1 video' : ''}\n${file}`);
